"""
Simulated Disaster Hazard Engine.
DISCLAIMER: All environmental data, plume dispersions, flood expansions, and earthquake 
radii generated by this engine are strictly simulated for testing and training purposes.
"""
from typing import Dict, Any, List
import time
import math

class SimulatedDisasterEngine:
    """
    Synthesizes dynamic disaster perimeter spread and affected cell metrics.
    """

    def __init__(self, scenario_name: str = "Synthetic Hazard Scenario Alpha"):
        self.scenario_name = scenario_name
        self.is_simulated = True

    def calculate_hazard_spread(
        self,
        center_lat: float,
        center_lng: float,
        elapsed_minutes: float,
        growth_rate_km_hr: float = 2.5,
    ) -> Dict[str, Any]:
        """
        Calculates expanding hazard radius and intensity rings based on simulated elapsed time.
        """
        effective_hours = max(0.0, elapsed_minutes / 60.0)
        current_radius_km = round(1.0 + (effective_hours * growth_rate_km_hr), 2)
        
        # Synthetic severity rating 1-5
        severity_index = min(5, max(1, math.ceil(current_radius_km / 3.0)))

        return {
            "scenario": self.scenario_name,
            "center": {"lat": center_lat, "lng": center_lng},
            "elapsed_minutes": elapsed_minutes,
            "current_radius_km": current_radius_km,
            "severity_index": severity_index,
            "is_simulated": True,
            "timestamp": time.time(),
        }
